-- =============================================================================
-- Painel de Entregas (Mantiqueira) — estrutura de dados do DER Iota.Hub
-- Fonte: "Proposta de estrutura de dados (DER)" — Lucas Lima / Iota.Hub, 27/10/2026
--
-- Segue o DER como proposto, com UMA adaptação:
--   * As tabelas `perfil` e `usuario` do DER NÃO são criadas. O acesso continua
--     no modelo já implementado (public.allowed_users + Supabase Auth + MFA).
--     Os campos que apontavam para `usuario.id` viram `*_email` com FK para
--     public.allowed_users(email).
--
-- Convenções
--   * Chaves: bigint identity (como no DER).
--   * dia_semana: ISO-8601 → 1 = segunda … 7 = domingo.
--   * Datas/horas: timestamptz; regras com vigência em `date` (como no DER).
--   * RLS: leitura/escrita para usuários da whitelist via public.is_allowed_user()
--     (sessões "confiar neste computador" ficam aal1, por isso não usamos aal2).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Enums
-- -----------------------------------------------------------------------------
create type public.status_area          as enum ('ATIVO', 'INATIVO');
create type public.nivel_regra          as enum ('CIDADE', 'BAIRRO', 'RUA');
create type public.acao_alteracao       as enum ('ATIVAR', 'INATIVAR', 'DIAS');
create type public.status_publicacao    as enum ('REVISAO', 'ENVIADO', 'SUCESSO', 'ERRO');
create type public.tipo_publicacao      as enum ('NORMAL', 'REPROCESSO', 'CORRECAO');
create type public.status_item          as enum ('PENDENTE', 'SUCESSO', 'ERRO');
create type public.tipo_sincronizacao   as enum ('AUTOMATICA', 'MANUAL', 'CARGA_INICIAL');
create type public.origem_sincronizacao as enum ('VTEX', 'PLANILHA');
create type public.status_sincronizacao as enum ('OK', 'FALHA');
create type public.status_assinatura    as enum ('ATIVA', 'PAUSADA', 'CANCELADA');
create type public.status_pedido        as enum ('GERADO', 'FATURADO', 'ENTREGUE', 'CANCELADO');
create type public.tipo_impacto         as enum ('PULA', 'DUPLICA', 'MUDA_DIA');
create type public.status_aviso         as enum ('PENDENTE', 'AVISADO', 'ACEITO');

-- =============================================================================
-- Domínio 1 — Geografia e regras de entrega
-- =============================================================================
create table public.estado (
  id            bigint generated by default as identity primary key,
  nome          varchar(80)  not null,
  sigla         char(2)      not null unique,
  status        public.status_area not null default 'INATIVO',
  atualizado_em timestamptz  not null default now()
);

create table public.cidade (
  id          bigint generated by default as identity primary key,
  estado_id   bigint not null references public.estado(id),
  nome        varchar(120) not null,
  codigo_ibge varchar(7)   not null unique,
  status      public.status_area not null default 'INATIVO',
  vtex_ref    varchar(120)
);
create index cidade_estado_idx on public.cidade(estado_id);

create table public.zona (
  id        bigint generated by default as identity primary key,
  cidade_id bigint not null references public.cidade(id),
  nome      varchar(80) not null,
  unique (cidade_id, nome)
);

create table public.bairro (
  id        bigint generated by default as identity primary key,
  cidade_id bigint not null references public.cidade(id),
  zona_id   bigint references public.zona(id),            -- opcional
  nome      varchar(120) not null,
  status    public.status_area not null default 'INATIVO',
  vtex_ref  varchar(120),
  unique (cidade_id, nome)
);
create index bairro_cidade_idx on public.bairro(cidade_id);
create index bairro_zona_idx   on public.bairro(zona_id);

create table public.rua (
  id                 bigint generated by default as identity primary key,
  bairro_id          bigint not null references public.bairro(id),
  logradouro         varchar(160) not null,
  cep                char(8) not null check (cep ~ '^[0-9]{8}$'),
  status             public.status_area not null default 'INATIVO',
  segue_regra_bairro boolean not null default true,
  vtex_ref           varchar(120)
);
create index rua_bairro_idx on public.rua(bairro_id);
create index rua_cep_idx    on public.rua(cep);

-- =============================================================================
-- Domínio 2 — Publicação e sincronização
-- (perfil/usuario do DER substituídos por public.allowed_users)
-- =============================================================================
create table public.publicacao (
  id                   bigint generated by default as identity primary key,
  autor_email          text not null references public.allowed_users(email),
  publicacao_origem_id bigint references public.publicacao(id),
  status               public.status_publicacao not null default 'REVISAO',
  tipo                 public.tipo_publicacao   not null default 'NORMAL',
  payload              jsonb,
  total_itens          int not null default 0,
  criado_em            timestamptz not null default now(),
  publicado_em         timestamptz,
  -- CORRECAO sempre aponta para a original; NORMAL nunca aponta
  constraint publicacao_origem_ck check (
    (tipo <> 'CORRECAO' or publicacao_origem_id is not null)
    and (tipo <> 'NORMAL' or publicacao_origem_id is null)
  )
);
create index publicacao_status_idx on public.publicacao(status);

-- regra_entrega depende de publicacao, por isso vem depois
create table public.regra_entrega (
  id              bigint generated by default as identity primary key,
  nivel           public.nivel_regra not null,
  cidade_id       bigint references public.cidade(id),
  bairro_id       bigint references public.bairro(id),
  rua_id          bigint references public.rua(id),
  publicacao_id   bigint references public.publicacao(id),  -- publicação que criou a regra
  vigencia_inicio date not null,
  vigencia_fim    date,                                     -- null = vigente
  -- só uma das três FKs, coerente com o nível
  constraint regra_entrega_nivel_ck check (
       (nivel = 'CIDADE' and cidade_id is not null and bairro_id is null and rua_id is null)
    or (nivel = 'BAIRRO' and bairro_id is not null and cidade_id is null and rua_id is null)
    or (nivel = 'RUA'    and rua_id    is not null and cidade_id is null and bairro_id is null)
  ),
  constraint regra_entrega_vigencia_ck check (vigencia_fim is null or vigencia_fim > vigencia_inicio)
);
create index regra_entrega_cidade_idx on public.regra_entrega(cidade_id) where cidade_id is not null;
create index regra_entrega_bairro_idx on public.regra_entrega(bairro_id) where bairro_id is not null;
create index regra_entrega_rua_idx    on public.regra_entrega(rua_id)    where rua_id    is not null;
-- no máximo uma regra vigente (vigencia_fim null) por área
create unique index regra_entrega_vigente_cidade_uq on public.regra_entrega(cidade_id) where vigencia_fim is null and nivel = 'CIDADE';
create unique index regra_entrega_vigente_bairro_uq on public.regra_entrega(bairro_id) where vigencia_fim is null and nivel = 'BAIRRO';
create unique index regra_entrega_vigente_rua_uq    on public.regra_entrega(rua_id)    where vigencia_fim is null and nivel = 'RUA';

create table public.regra_entrega_dia (
  id         bigint generated by default as identity primary key,
  regra_id   bigint not null references public.regra_entrega(id) on delete cascade,
  dia_semana smallint not null check (dia_semana between 1 and 7),
  unique (regra_id, dia_semana)
);

create table public.rascunho_alteracao (
  id             bigint generated by default as identity primary key,
  usuario_email  text not null references public.allowed_users(email),
  publicacao_id  bigint references public.publicacao(id),  -- null = ainda não publicado
  entidade_tipo  public.nivel_regra not null,
  entidade_id    bigint not null,
  acao           public.acao_alteracao not null,
  valor_anterior jsonb,
  valor_novo     jsonb,
  criado_em      timestamptz not null default now()
);
create index rascunho_pendente_idx on public.rascunho_alteracao(criado_em) where publicacao_id is null;
create index rascunho_publicacao_idx on public.rascunho_alteracao(publicacao_id);

create table public.publicacao_item (
  id             bigint generated by default as identity primary key,
  publicacao_id  bigint not null references public.publicacao(id) on delete cascade,
  entidade_tipo  public.nivel_regra not null,
  entidade_id    bigint not null,
  acao           public.acao_alteracao not null,
  valor_anterior jsonb,
  valor_novo     jsonb,
  status_item    public.status_item not null default 'PENDENTE'
);
create index publicacao_item_publicacao_idx on public.publicacao_item(publicacao_id);

create table public.publicacao_envio (
  id              bigint generated by default as identity primary key,
  publicacao_id   bigint not null references public.publicacao(id) on delete cascade,
  tentativa       int not null default 1,
  request_payload jsonb,
  http_status     int,
  response_body   jsonb,
  erro            text,
  enviado_em      timestamptz not null default now(),
  unique (publicacao_id, tentativa)
);

create table public.sincronizacao (
  id              bigint generated by default as identity primary key,
  usuario_email   text references public.allowed_users(email),  -- null = automática
  tipo            public.tipo_sincronizacao   not null,
  origem          public.origem_sincronizacao not null default 'VTEX',
  status          public.status_sincronizacao not null,
  registros_lidos int not null default 0,
  erro            text,
  iniciada_em     timestamptz not null default now(),
  finalizada_em   timestamptz
);
create index sincronizacao_iniciada_idx on public.sincronizacao(iniciada_em desc);

