  unique (analise_id, assinatura_id)
);

-- =============================================================================
-- View de precedência: Rua > Bairro > Cidade (regras vigentes hoje)
-- `ativa_efetiva`: premissa do DER — inativar cidade/bairro bloqueia as ruas
-- por precedência, sem cascata no status das ruas.
-- =============================================================================
create or replace view public.vw_regra_efetiva_rua
with (security_invoker = true) as
with vigentes as (
  select r.*
  from public.regra_entrega r
  where r.vigencia_inicio <= current_date
    and (r.vigencia_fim is null or r.vigencia_fim > current_date)
),
dias as (
  select regra_id, array_agg(dia_semana order by dia_semana) as dias
  from public.regra_entrega_dia
  group by regra_id
)
select
  ru.id                                   as rua_id,
  ru.bairro_id,
  b.cidade_id,
  ru.logradouro,
  ru.cep,
  coalesce(rr.id, rb.id, rc.id)           as regra_id,
  case when rr.id is not null then 'RUA'
       when rb.id is not null then 'BAIRRO'
       when rc.id is not null then 'CIDADE' end::public.nivel_regra as nivel_origem,
  coalesce(dr.dias, db.dias, dc.dias)     as dias,
  (ru.status = 'ATIVO' and b.status = 'ATIVO' and c.status = 'ATIVO' and e.status = 'ATIVO') as ativa_efetiva
from public.rua ru
join public.bairro b on b.id = ru.bairro_id
join public.cidade c on c.id = b.cidade_id
join public.estado e on e.id = c.estado_id
left join vigentes rr on rr.nivel = 'RUA'    and rr.rua_id    = ru.id and ru.segue_regra_bairro = false
left join vigentes rb on rb.nivel = 'BAIRRO' and rb.bairro_id = b.id
left join vigentes rc on rc.nivel = 'CIDADE' and rc.cidade_id = c.id
left join dias dr on dr.regra_id = rr.id
left join dias db on db.regra_id = rb.id
left join dias dc on dc.regra_id = rc.id;

-- =============================================================================
-- RLS — acesso para usuários da whitelist
-- =============================================================================
do $$
declare t text;
begin
  foreach t in array array[
    'estado','cidade','zona','bairro','rua','regra_entrega','regra_entrega_dia',
    'rascunho_alteracao','publicacao','publicacao_item','publicacao_envio','sincronizacao',
    'cliente','endereco','assinatura','pedido_ciclo','analise_impacto','impacto_assinatura'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (public.is_allowed_user()) with check (public.is_allowed_user())',
      t || '_allowed_users', t);
  end loop;
end $$;

grant select on public.vw_regra_efetiva_rua to authenticated;
